"""Deterministic dependency-free JSON Schema to TypeScript for the browser wire only."""

import json
from pathlib import Path

from api.app.wire import MODELS

ROOT = Path(__file__).resolve().parents[1]


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(s) for s in schema["anyOf"])
    kind = schema.get("type")
    if kind == "object":
        required = schema.get("required", [])
        return (
            "{ "
            + " ".join(
                json.dumps(k) + ("" if k in required else "?") + ": " + ts(v) + ";"
                for k, v in schema["properties"].items()
            )
            + " }"
        )
    if kind == "array":
        return "Array<" + ts(schema["items"]) + ">"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }[kind]


def artifacts():
    definitions = {}
    for model in MODELS:
        schema = model.model_json_schema(ref_template="#/$defs/{model}")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    schemas = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "urn:proofflow:browser:v1",
        "$defs": dict(sorted(definitions.items())),
    }
    types = "// Generated by scripts/generate_browser_types.py. Do not edit.\n"
    types += "// Structural wire types; server validation and authorization remain required.\n"
    types += (
        "\n".join("export type " + k + " = " + ts(v) + ";" for k, v in sorted(definitions.items()))
        + "\n"
    )
    return {
        "contracts/browser-v1.schema.json": json.dumps(schemas, indent=2) + "\n",
        "contracts/browser-v1.d.ts": types,
    }


def main():
    for path, content in artifacts().items():
        (ROOT / path).write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
